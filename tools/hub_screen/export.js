// Writes the fonts and sample artwork the Hub firmware draws with:  node export.js
//   -> firmware/hub/fonts.h, firmware/hub/art.h
const fs = require("fs");
const path = require("path");
const { FONTS, MESSAGE, ICONS, ICONS_SMALL, ICON_NAMES } = require("./screens");

const OUT = path.join(__dirname, "..", "..", "firmware", "hub");
const cName = (key) => "FONT_" + key.replace(/([A-Z])/g, "_$1").toUpperCase();
const hex = (bytes) => {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 20) lines.push("  " + Array.from(bytes.slice(i, i + 20), (b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
  return lines.join("\n");
};

// Each glyph row is padded to a whole byte, most significant bit first
function packGlyph(g) {
  const stride = Math.ceil(g.w / 8);
  const out = new Uint8Array(stride * g.h);
  g.rows.forEach((row, y) => { for (let x = 0; x < g.w; x++) if (row[x] === "1") out[y * stride + (x >> 3)] |= 0x80 >> (x & 7); });
  return out;
}

let fonts = `// Generated by tools/hub_screen/export.js - do not edit by hand.
// Bitmap fonts at the exact pixel sizes the screen uses, made from:
//   Inter - Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter)
//   Tiny5 - Copyright 2022-2024 The Tiny5 Project Authors (https://github.com/Gissio/font_tiny5)
// Both are licensed under the SIL Open Font License, Version 1.1: see OFL.txt in this folder.
// The glyphs are converted to 1-bit bitmaps; the "emboldened" Tiny5 sets are widened by one pixel.
#pragma once
#include <stdint.h>

struct Glyph {
  uint16_t code;     // Unicode code point
  uint8_t w, h;      // bitmap size
  int8_t xo, yo;     // bitmap position relative to the pen and the baseline
  uint8_t advance;   // pen movement after the glyph
  uint16_t offset;   // start of the bitmap in the font's bits: rows padded to a byte, most significant bit first
};

struct Font {
  const Glyph* glyphs;
  uint8_t count;
  const uint8_t* bits;
};
`;

let total = 0;
for (const [key, font] of Object.entries(FONTS)) {
  const name = cName(key);
  const glyphs = Object.values(font.glyphs).sort((a, b) => a.ch.codePointAt(0) - b.ch.codePointAt(0));
  const chunks = [];
  let offset = 0;
  const rows = glyphs.map((g) => {
    const bits = packGlyph(g);
    chunks.push(bits);
    const line = `  {${g.ch.codePointAt(0)}, ${g.w}, ${g.h}, ${g.xo}, ${g.yo}, ${g.adv}, ${offset}},  // ${g.ch === " " ? "space" : g.ch === "\\" ? "backslash" : g.ch}`;
    offset += bits.length;
    return line;
  });
  if (offset > 65535 || glyphs.length > 255) throw new Error(name + " is too big for the Glyph fields");
  // The firmware's text decoder reads one- and two-byte UTF-8 only
  if (glyphs.some((g) => g.ch.codePointAt(0) > 0x7ff)) throw new Error(name + " has a character the firmware cannot decode");
  total += offset + glyphs.length * 10;
  fonts += `\n// ${font.alias} ${font.size} px${font.bold ? ", emboldened" : ""}\n`;
  fonts += `static const uint8_t ${name}_BITS[] = {\n${hex(Buffer.concat(chunks.map((c) => Buffer.from(c))))}\n};\n`;
  fonts += `static const Glyph ${name}_GLYPHS[] = {\n${rows.join("\n")}\n};\n`;
  fonts += `static const Font ${name} = {${name}_GLYPHS, ${glyphs.length}, ${name}_BITS};\n`;
}

const bitmap = (name, frame, comment) =>
  `\n// ${comment}\nstatic const uint16_t ${name}_W = ${frame.w}, ${name}_H = ${frame.h};\nstatic const uint8_t ${name}[] = {\n${hex(frame.packed())}\n};\n`;

let art = `// Generated by tools/hub_screen/export.js - do not edit by hand.
// 1-bit bitmaps: rows padded to a whole byte, most significant bit first, 1 = black.
#pragma once
#include <stdint.h>
`;
art += bitmap("ART_MESSAGE_SAMPLE", MESSAGE, "Sample message, drawn on a canvas the way the web app will. Lettering: Caveat, Copyright 2014 The Caveat Project Authors, SIL Open Font License 1.1 (see OFL.txt)");
// Weather icons, in two sizes: the smaller set is used when the low-battery band takes 12 px of the area
art += `\nenum WeatherIcon { ${ICON_NAMES.map((n) => "ICON_" + n.toUpperCase()).join(", ")}, ICON_COUNT };\n`;
art += "struct Icon {\n  const uint8_t* bits;\n  uint8_t w, h;\n};\n";
for (const [suffix, set] of [["", ICONS], ["_SMALL", ICONS_SMALL]]) {
  for (const n of ICON_NAMES) art += `\nstatic const uint8_t ART_${n.toUpperCase()}${suffix}[] = {\n${hex(set[n].packed())}\n};\n`;
  art += `\nstatic const Icon ART_WEATHER${suffix}[ICON_COUNT] = {\n${ICON_NAMES.map((n) => `  {ART_${n.toUpperCase()}${suffix}, ${set[n].w}, ${set[n].h}},`).join("\n")}\n};\n`;
}

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "fonts.h"), fonts);
fs.writeFileSync(path.join(OUT, "art.h"), art);
console.log(`fonts.h: ${Object.keys(FONTS).length} fonts, about ${total} bytes of flash; art.h: ${MESSAGE.packed().length + ICON_NAMES.reduce((n, k) => n + ICONS[k].packed().length + ICONS_SMALL[k].packed().length, 0)} bytes`);
